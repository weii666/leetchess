/**
 * 完成狀態:一份題號集合,存在瀏覽器本機。
 *
 * 系統不偵測解題成功,所以進度模型就是「哪些題號被使用者按過」——
 * **本模組是這份狀態的唯一寫入處**(problem-browser 3.1、3.2、3.3)。
 *
 * 與 `catalog.js`、`fen.js` 同層:**不得 import 任何其他 web 模組**,也不碰 DOM。
 * 呈現、完成計數與視覺區分都是 `list.js` 的事;這裡只有資料。這使它能單獨被載進
 * 瀏覽器以 `page.evaluate()` 驗證。
 *
 * ## 這份狀態不是列表的鏡像
 *
 * 集合是**題號的集合**,不是「目前列出哪些題」的投影(3.7)。題目可能因為被標為
 * 不可解而下架,日後又重新上架;若拿列表去反向修剪集合,使用者的標記就會在那次
 * 下架時被靜靜抹掉。本模組因此連「目前列出哪些題」這個輸入都沒有 ——
 * `loadCompleted()` 不收參數,也就沒有修剪的機會。
 *
 * ## 儲存區壞掉時發生什麼事
 *
 * 判準只有一條:**任何一種儲存異常都不該讓列表打不開**(3.6)。真正要擋的遠不只
 * `JSON.parse` 拋錯:
 *
 * - 取用 `localStorage` 這個屬性本身就可能拋(隱私模式、跨站儲存被擋),或根本不存在
 * - `getItem` / `setItem` 各自可能拋(政策封鎖、配額上限)
 * - 存的值解析得出來但型別不對(物件、數字、字串)
 * - 陣列裡混著不是題號的東西
 *
 * 每一種都收斂成同一個結果:讀不到就是「全部未完成」,寫不進去就安靜地算了。
 * 使用者不會看到任何錯誤 —— 那是本機資料的技術細節,他無從處理,而列表完全可用。
 */

/**
 * 完成狀態的儲存鍵。
 *
 * **中段的 `v1` 是版本前綴**,日後格式若要改(例如加入練習次數或時間),舊鍵可以
 * 辨識而不會被新版本誤讀成自己的格式 —— 換格式就換版本號,舊值自然被忽略而不是
 * 被硬解。值是數字題號的 JSON 陣列。
 */
export const STORAGE_KEY = 'leetchess:v1:completed';

/**
 * 本機儲存區,取不到時為 `null`。
 *
 * **每次都重新取,不在模組載入時抓一份。** 取用這個屬性本身在隱私模式或跨站儲存
 * 被擋時就會拋,若在載入時取,整個模組會 import 不進去 —— 那正是「讓列表打不開」。
 */
const storage = () => {
  try {
    return globalThis.localStorage ?? null;
  } catch {
    return null;
  }
};

/**
 * 這是不是一個題號。
 *
 * 題號是正整數(題目 schema 的主鍵)。字串型的 `'2'` 也一律不收:悄悄轉型會讓
 * 儲存區裡同時出現 `2` 與 `'2'` 兩種寫法,而集合對它們的判定並不相同 —— 同一題
 * 會變成兩筆,取消標記也就取消不掉。
 */
const isPositionId = (value) => Number.isInteger(value) && value > 0;

/** 把任何一堆東西收斂成一組乾淨的題號。 */
const toIds = (values) => new Set([...(values ?? [])].filter(isPositionId));

/**
 * 讀出目前的完成題號(3.3、3.6)。
 *
 * **讀取不寫入任何東西**(3.4)。讀到壞掉的值時不「順手修好」它:自動改寫看似
 * 體貼,實際上是在使用者沒有操作的情況下改動他的資料,若那份損毀其實來自一個
 * 還沒發布的新格式,一次讀取就會把它輾掉。
 *
 * 陣列裡混著雜物時**丟掉雜物而不是丟掉整份進度**。整份丟掉同樣能讓列表打得開,
 * 但那會因為一筆髒資料抹掉使用者其餘的標記 —— 3.6 要的是「以全部未完成繼續
 * 運作」,而不是「有機會就清空」。認不得的整份值(不是 JSON、不是陣列)才退回
 * 全部未完成。
 *
 * @returns {Set<number>} 完成的題號。讀不到或認不得時是空集合。
 */
export function loadCompleted() {
  const store = storage();
  if (store === null) return new Set();

  let stored;
  try {
    stored = store.getItem(STORAGE_KEY);
  } catch {
    return new Set(); // 讀取被政策擋下 —— 與「還沒存過」同樣處理
  }

  let parsed;
  try {
    // 鍵不存在時 `stored` 是 `null`,解析後同樣不是陣列而落到下面的空集合 ——
    // 「還沒存過」與「認不得」對這裡是同一件事:沒有可用的完成狀態。
    parsed = JSON.parse(stored);
  } catch {
    return new Set();
  }
  // 解析得出來但形狀不對(物件、數字、字串、null)一律視為認不得。
  if (!Array.isArray(parsed)) return new Set();

  return toIds(parsed);
}

/**
 * 把一組題號寫進儲存區。**失敗一律安靜地算了。**
 *
 * 永遠寫入完整的一份(即使是空陣列),不做增量:集合小(500 題也只有幾 KB),
 * 而「整份取代」使儲存區裡不可能留下前一次的殘骸。
 *
 * 題號依序寫出,使同一組完成狀態永遠得到同一個字串 —— 存進去的東西使用者看得到
 * (開發者工具就能開),遞增的題號讀得懂,而順序不隨操作歷程漂移。
 */
function writeIds(completed) {
  const store = storage();
  if (store === null) return;
  try {
    store.setItem(
      STORAGE_KEY,
      JSON.stringify([...completed].sort((a, b) => a - b)),
    );
  } catch {
    // 配額爆掉、被政策擋下 —— 見 `toggleCompleted` 對這件事的取捨說明。
  }
}

/**
 * 切換一題的完成標記(3.1、3.2),並盡力寫入本機。
 *
 * 傳入目前的集合、回傳新的集合,**不就地修改**:呼叫端以
 * `completed = toggleCompleted(completed, id)` 取得新狀態,立即重繪即可(3.2)。
 *
 * **寫入失敗不往上拋,也不把切換退回去。**
 *
 * 這是類推,不是引用:requirements 3.6 與 design 的 Error Handling 講的都是
 * **讀取端**(「先前儲存的完成狀態無法解析」「完成狀態損毀」),寫入端沒有明文。
 * 把同一個態度延伸過來的理由是 3.2 —— 切換必須「立即反映」,而拋錯或把切換退
 * 回去都會讓核取方塊按下去沒有反應,直接牴觸它。至於不告知,是因為寫不進去的
 * 原因(隱私模式、儲存被擋、配額爆掉)使用者一個都處理不了。代價是關掉分頁後
 * 標記不會留著 —— 但在儲存區不可用的情況下,那本來就留不住。
 *
 * 日後若判斷該讓使用者知道「這個瀏覽器存不住進度」,**不需要動這個函式的簽章**:
 * 補一個 `storageAvailable()` 之類的獨立匯出即可,對既有呼叫端是純粹的新增。
 *
 * 狀態由呼叫端持有而非每次從儲存區重新推導,理由不是別無選擇(模組內留一份
 * 記憶體鏡像同樣做得到),而是 design 把本模組定為「純函式 + localStorage」、
 * 依賴為「無」—— 模組級的可變狀態與那個定位相衝。這個形狀順帶也擋掉一個實際
 * 的壞結果:儲存區讀不到時,每次切換都會從空集合重新出發,標記按得上去卻永遠
 * 取消不掉。
 *
 * 不是題號的值(字串、負數、小數、空值)一律忽略,連寫都不寫:讀的時候擋得住,
 * 寫的時候也不放進去,壞資料才不會在下一次讀取時變成使用者的損失。
 *
 * @param {Iterable<number>} completed 目前的完成題號。
 * @param {number} id 要切換的題號。
 * @returns {Set<number>} 切換後的完成題號。
 */
export function toggleCompleted(completed, id) {
  const next = toIds(completed);
  if (!isPositionId(id)) return next;

  if (!next.delete(id)) next.add(id);
  writeIds(next);
  return next;
}
